const geoGerman = Object.fromEntries(Object.entries(geoEnglish).map(([german, english]) => [english, german]));

export function translateGeo(message: string, language: GeoLanguage, values: Record<string, string | number> = {}) {
  const translated = language === 'en' ? geoEnglish[message] || message : geoGerman[message] || message;
  return translated.replace(/\{(\w+)\}/g, (placeholder, key: string) => Object.hasOwn(values, key) ? String(values[key]) : placeholder);
}
